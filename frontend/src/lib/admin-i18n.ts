export function contentLocaleFromPath(locale: string | undefined): AdminContentLocale {
  if (locale === 'zh' || locale === 'zh-Hant') return 'zh';
  if (locale === 'fr') return 'fr';
  return 'en';
}

export function adminUiText(locale: string | undefined) {
  const normalized: AdminUiLocale = contentLocaleFromPath(locale);
  return uiText[normalized];
}

export function adminContentLanguageOptions(locale: string | undefined) {
  const labels = adminUiText(locale).common.languageNames;
  return [
    { value: 'zh' as const, label: labels.zh },
    { value: 'en' as const, label: labels.en },
    { value: 'fr' as const, label: labels.fr },
  ];
}
